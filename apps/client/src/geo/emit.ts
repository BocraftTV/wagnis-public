// Writes the generated map data module (maps/welt.shapes.ts): flat number lists per ring, main part first.
import type { Rings } from "./notch.js";

export function shapesModule(rings: Rings, source: string): string {
  const ids = Object.keys(rings).sort();
  const body = ids
    .map((id) => {
      const lists = rings[id]!.map((ring) => `[${ring.map((p) => `${p[0]}, ${p[1]}`).join(", ")}]`);
      return `  ${id}: [\n${lists.map((l) => `    ${l},`).join("\n")}\n  ],`;
    })
    .join("\n");
  return `// GENERATED by scripts/build-world-shapes.mjs (plan 006). Do not edit by hand: change geo/welt.regions.ts and run
// the script again. ${source}
// Outlines of the 42 territories in map units (viewBox 1000 x 540): one flat list [x0, y0, x1, y1, ...] per ring,
// main part (largest area) first, islands after it. Neighbouring territories share their border points exactly.
import type { Point } from "../lib/viewport.js";

const flat: Record<string, readonly (readonly number[])[]> = {
${body}
};

function points(list: readonly number[]): Point[] {
  return Array.from({ length: list.length / 2 }, (_, i) => ({ x: list[2 * i]!, y: list[2 * i + 1]! }));
}

export const weltShapes: Record<string, readonly (readonly Point[])[]> = Object.fromEntries(
  Object.entries(flat).map(([id, rings]) => [id, rings.map(points)]),
);
`;
}
